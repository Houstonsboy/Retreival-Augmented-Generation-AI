# DEFICIENCY REPORT layout
# ---------------------------------------------------------------------------

def _render_deficiency_report(record: dict) -> FPDF:
    cert_number = record.get("certificate_number", "")
    created_at  = record.get("created_at", "")
    if hasattr(created_at, "isoformat"):
        created_at = created_at.isoformat()
    created_at  = str(created_at)[:10]

    gate     = record.get("gate") or {}
    summary  = record.get("analysis_summary") or {}
    evidence = record.get("evidence") or []
    conditions = gate.get("conditions") or []
    outcome  = gate.get("outcome", "weak")

    pdf = _CertPDF(cert_number, created_at)
    pdf.set_creation_date(_parse_created_at(created_at))  # deterministic metadata

    # Title
    pdf.set_font(FONT, style="B", size=13)
    pdf.multi_cell(
        0, 8,
        "Evidence Admissibility Report\n"
        "Section 106B, Evidence Act (Cap. 80): Requirements Not Yet Met",
        align="C",
    )
    pdf.ln(3)

    # Plain-language summary
    pdf.section_heading("Summary")
    if outcome == "needs_strengthening":
        pdf.body(
            "Your evidence satisfies the technical integrity checks but some "
            "information about the device that produced the evidence is missing "
            "or could not be confirmed. Address the items listed below before "
            "submitting your evidence to the court."
        )
    else:
        pdf.body(
            "Your evidence could not pass the Section 106B admissibility check "
            "because one or more fundamental integrity requirements were not met. "
            "Review the items below carefully."
        )

    # Conditions table
    pdf.section_heading("Section 106B Requirements")
    col_w = [15, 95, 60]
    pdf.set_font(FONT, style="B", size=9)
    for h, w in zip(["Ref.", "Requirement", "What to do next"], col_w):
        pdf.cell(w, 7, h, border=1)
    pdf.ln()

    pdf.set_font(FONT, size=9)
    for cond in conditions:
        code  = _safe(cond.get("code", ""))
        title = _safe(cond.get("title", ""))
        met   = cond.get("met", False)
        remedy = _safe(cond.get("remedy") or "—")
        status = "Met" if met else "NOT MET"

        pdf.cell(col_w[0], 7, code, border=1)
        # title + status in same cell
        label = f"[{status}] {title}"
        pdf.set_font(FONT, style="B" if not met else "", size=9)
        pdf.cell(col_w[1], 7, label[:55], border=1)
        pdf.set_font(FONT, size=9)
        pdf.multi_cell(col_w[2], 7, remedy[:120], border=1)
        # multi_cell already moved to next line

    pdf.ln(3)

    # Other evidence gaps from analysis
    missing = _safe_list(summary.get("missing_information") or [])[:10]
    checklist = _safe_list(summary.get("strengthen_checklist") or [])[:10]

    if missing or checklist:
        pdf.section_heading("Other Gaps Found in Your Evidence")
        if missing:
            pdf.set_font(FONT, style="B", size=10)
            pdf.cell(0, 6, "Missing information:", new_x="LMARGIN", new_y="NEXT")
            for item in missing:
                pdf.bullet(item)
        if checklist:
            pdf.set_font(FONT, style="B", size=10)
            pdf.cell(0, 6, "Steps to strengthen your evidence:", new_x="LMARGIN", new_y="NEXT")
            for item in checklist:
                pdf.bullet(item)
        pdf.ln(2)

    # Evidence schedule
    pdf.section_heading("Evidence Schedule")
    _add_evidence_schedule(pdf, evidence)

    # Disclaimer
    disc = summary.get("disclaimer") or ""
    if disc:
        pdf.set_font(FONT, style="I", size=9)
        pdf.set_text_color(100, 100, 100)
        pdf.multi_cell(0, 5, _safe(disc))
        pdf.set_text_color(0, 0, 0)

    return pdf


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def render_pdf(record: dict) -> bytes:
    """Generate certificate or deficiency report PDF bytes from a stored record.

    ``record`` is the dict stored in Firestore by certificate_store.
    Deterministic for the same record (uses record["created_at"] for metadata).
    """
    document_type = (record.get("gate") or {}).get("document_type", "DEFICIENCY_REPORT")

    if document_type == "CERTIFICATE":
        pdf = _render_certificate(record)
    else:
        pdf = _render_deficiency_report(record)

    buf = BytesIO()
    pdf.output(buf)
    return buf.getvalue()
