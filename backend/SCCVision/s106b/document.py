# CERTIFICATE layout
# ---------------------------------------------------------------------------

def _parse_created_at(created_at: str) -> datetime.datetime:
    """Parse a date string to a UTC datetime for deterministic PDF metadata."""
    try:
        date_part = str(created_at)[:10]  # "YYYY-MM-DD"
        return datetime.datetime(
            int(date_part[:4]), int(date_part[5:7]), int(date_part[8:10]),
            tzinfo=datetime.timezone.utc,
        )
    except (ValueError, IndexError):
        return datetime.datetime(2000, 1, 1, tzinfo=datetime.timezone.utc)


def _render_certificate(record: dict) -> FPDF:
    cert_number = record.get("certificate_number", "")
    created_at  = record.get("created_at", "")
    if hasattr(created_at, "isoformat"):
        created_at = created_at.isoformat()
    created_at = str(created_at)[:10]

    device      = record.get("device_facts") or {}
    evidence    = record.get("evidence") or []
    gate        = record.get("gate") or {}
    conditions  = gate.get("conditions") or []

    prod_method = device.get("production_method", "")
    prod_label  = _PRODUCTION_METHOD_LABELS.get(prod_method, prod_method)
    last4       = device.get("phone_number_last4") or ""
    phone_disp  = device.get("phone_number") or (f"******{last4}" if last4 else "(not provided)")

    pdf = _CertPDF(cert_number, created_at, certificate=True)
    pdf.set_creation_date(_parse_created_at(created_at))
    pdf.set_font(FONT, style="BU", size=11)
    pdf.multi_cell(
        0, 5.5,
        "CERTIFICATE UNDER SECTION 106B(4) OF THE EVIDENCE ACT\n"
        "(CAP. 80, LAWS OF KENYA)",
        align="C", new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(4)

    declarant = device.get("declarant_name") or "________________________"
    position = device.get("declarant_position") or "________________________"
    make = device.get("device_make") or "________________"
    model = device.get("device_model") or "________________"
    pdf.body(f"I, {declarant}, in my capacity as {position}, certify as follows:")
    pdf.list_item("1.", "I am familiar with the device and the manner in which the records were produced.")
    pdf.list_item(
        "2.",
        "The electronic records identified in the attached Schedule were produced using "
        f"the following method: {prod_label or '________________'}. "
        f"Device make and model: {make} {model}. Phone number: {phone_disp}.",
    )

    c_statements = {
        "2a": (
            "During the period covered by these records, the device was regularly "
            "used by me and was under my lawful control."
        ),
        "2b": (
            "Information of the kind contained in the electronic records (messages "
            "and/or M-Pesa transactions) was regularly fed into the device in the "
            "ordinary course of my activities during that period."
        ),
        "2c_ok": (
            "Throughout the material period the device was operating properly, "
            "and no malfunction affected the accuracy of the records."
        ),
        "2d": (
            "The information in the electronic records reproduces, or is derived "
            "from, information fed into the device in the ordinary course of those "
            "activities."
        ),
    }

    # Determine 2c statement
    cond_2c = next((c for c in conditions if c.get("code") == "2c"), None)
    if cond_2c and cond_2c.get("met"):
        mal_det = device.get("malfunction_details")
        if mal_det and not device.get("operating_properly", True):
            stmt_2c = (
                f"During the material period the device experienced a malfunction "
                f"({_safe(mal_det)}), but this malfunction did not affect the "
                "electronic record or the accuracy of its contents."
            )
        else:
            stmt_2c = c_statements["2c_ok"]
    else:
        stmt_2c = None  # 2c unmet — should not reach CERTIFICATE path

    statements = (
        c_statements["2a"],
        c_statements["2b"],
        stmt_2c,
        c_statements["2d"],
        "The Schedule identifies each record by file name and includes its SHA-256 "
        "fingerprint where available.",
        "The statements above are true to the best of my knowledge and belief.",
    )
    for number, statement in enumerate((item for item in statements if item), start=3):
        pdf.list_item(f"{number}.", statement)
    pdf.signature_fields()

    pdf.add_page()
    pdf.set_font(FONT, style="BU", size=13)
    pdf.cell(0, 7, "SCHEDULE", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font(FONT, style="I", size=10)
    pdf.cell(
        0, 6, "Electronic records referred to in paragraph 2 of the Certificate",
        align="C", new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(3)
    _add_evidence_schedule(pdf, evidence, court_style=True)
    with pdf.unbreakable() as verification:
        verification.set_font(FONT, size=10)
        verification.multi_cell(
            0, 5,
            "Verification. A matching SHA-256 fingerprint confirms that a file is "
            "identical to the file represented by the fingerprint in the Schedule.",
            border=1, padding=2, align="L", new_x="LMARGIN", new_y="NEXT",
        )
        verification.ln(4)

    if pdf.will_page_break(24):
        pdf.add_page()
    pdf.set_y(max(pdf.y, pdf.page_break_trigger - 24))
    with pdf.unbreakable() as filing:
        filing.set_font(FONT, style="B", size=9)
        filing.cell(85, 5, "DRAWN & FILED BY")
        filing.cell(85, 5, "TO BE SERVED UPON", new_x="LMARGIN", new_y="NEXT")
        filing.set_font(FONT, size=9)
        for left, right in (
            ("Name: ___________________________", "Name: ___________________________"),
            ("Address: _________________________", "Address: _________________________"),
            ("Tel./Email: ________________________", "Tel./Email: ________________________"),
        ):
            filing.cell(85, 4.5, left)
            filing.cell(85, 4.5, right, new_x="LMARGIN", new_y="NEXT")
        filing.ln(5)

    pdf.add_page()
    _add_contract_analysis_section(pdf, record, "Appendix — Contract Analysis")

    return pdf


