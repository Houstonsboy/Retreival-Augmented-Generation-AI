"""Generate Section 106B certificate or deficiency report PDFs with fpdf2.

render_pdf(record) → bytes

The function is deterministic for the same record: it uses record["created_at"]
(not the current time) so the same record always produces the same bytes after
normalising fpdf2's creation-date metadata field.
"""

from __future__ import annotations

import datetime
from pathlib import Path

from fpdf import FPDF, FontFace  # fpdf2


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

FONT = "Times"
_INK = (29, 37, 32)
_RULE = (108, 120, 112)
_TABLE_HEADING = FontFace(emphasis="BOLD", fill_color=(232, 237, 233))
_COAT_OF_ARMS = Path(__file__).with_name("assets") / "kenya-coat-of-arms.jpeg"

_FOOTER_TEXT = (
    "Generated by the SCC Evidence Assistant (prototype). "
    "This draft is not legal advice and has no legal effect until reviewed "
    "and signed by the declarant."
)
_HEADER_TEXT = "DRAFT - FOR REVIEW AND SIGNATURE"

# Map ProductionMethod values to plain-language descriptions
_PRODUCTION_METHOD_LABELS = {
    "screenshot_on_device": "Screenshot taken on the device that holds the messages",
    "forwarded_or_copied":  "Forwarded or copied from another device",
    "printed_statement":    "Printed statement produced by the device",
    "other":                "Other (not specified)",
}

_EVIDENCE_TYPE_LABELS = {
    "chat_screenshot": "Chat conversation",
    "mpesa_screenshot": "M-Pesa transaction",
    "other": "Other electronic record",
}

# Contract element labels (matches frontend ELEMENT_LABELS)
_ELEMENT_LABELS: dict = {
    "A": "Parties & identity",
    "B": "Capacity",
    "C": "Offer",
    "D": "Acceptance",
    "E": "Consideration",
    "F": "Intention",
    "G": "Certainty",
    "H": "Genuine consent",
    "I": "Legality",
    "J": "Formalities",
    "K": "Performance & breach",
}

_ELEMENT_DESC: dict = {
    "A": "Identity of both parties to the agreement",
    "B": "Legal capacity of both parties to contract",
    "C": "A specific proposal to contract on defined terms",
    "D": "Unambiguous agreement to those terms",
    "E": "The price, payment, or value exchanged",
    "F": "An intention to create a binding legal relationship",
    "G": "The subject matter of the contract is sufficiently clear",
    "H": "No duress, fraud, or misrepresentation",
    "I": "The agreement is for a lawful purpose",
    "J": "Any required formalities (e.g. writing, witnesses)",
    "K": "What was performed and whether obligations were met",
}

# Zapf Dingbats encodes the check mark and cross as "3" and "7".
_MET_STATUSES = {"PRESENT", "NO_ISSUE_INDICATED", "NOT_REQUIRED"}
_UNMET_STATUSES = {"ABSENT", "PARTIAL", "UNCLEAR"}
_TICK = FontFace(
    family="ZapfDingbats", size_pt=11, color=(27, 105, 59), fill_color=(224, 242, 230),
)
_CROSS = FontFace(
    family="ZapfDingbats", size_pt=11, color=(151, 42, 42), fill_color=(251, 230, 230),
)


# ---------------------------------------------------------------------------
# Windows-1252 sanitisation (fpdf2 core fonts are Windows-1252)
# ---------------------------------------------------------------------------

def _safe(text: str) -> str:
    """Replace characters outside Windows-1252 with '?'."""
    if not text:
        return ""
    return text.encode("cp1252", errors="replace").decode("cp1252")


def _safe_list(items: list) -> list[str]:
    return [_safe(str(i)) for i in items if i]


# ---------------------------------------------------------------------------
# Base PDF class
# ---------------------------------------------------------------------------

class _CertPDF(FPDF):
    def __init__(self, cert_number: str, created_at: str, *, certificate: bool = False):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.core_fonts_encoding = "cp1252"
        self._cert_number = _safe(cert_number)
        self._created_at = _safe(created_at[:10])
        self._certificate = certificate
        self.set_margins(20, 15, 20)
        self.set_auto_page_break(auto=True, margin=22)
        self.alias_nb_pages()
        self.add_page()
        self.set_text_color(*_INK)
        self.set_draw_color(*_RULE)

    def header(self):
        self.set_text_color(*_INK)
        if self._certificate:
            self.court_header()
            return

        self.set_font("Helvetica", style="B", size=8)
        self.set_text_color(126, 42, 42)
        self.cell(0, 5, _HEADER_TEXT, align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(*_INK)
        self.set_font("Helvetica", size=8)
        self.multi_cell(
            0, 5, f"Reference: {self._cert_number}    |    Prepared: {self._created_at}",
            align="C", new_x="LMARGIN", new_y="NEXT",
        )
        self.ln(2)
        self._rule()
        self.ln(4)

    def court_header(self):
        self.set_font("Helvetica", style="B", size=68)
        self.set_text_color(239, 235, 226)
        with self.rotation(32, x=self.w / 2, y=self.h / 2):
            self.text((self.w - self.get_string_width("DRAFT")) / 2, self.h / 2, "DRAFT")

        self.set_font("Helvetica", style="B", size=8)
        self.set_text_color(126, 42, 42)
        self.cell(self.epw / 2, 5, _HEADER_TEXT, align="L")
        self.set_text_color(*_INK)
        self.set_font("Helvetica", size=8)
        self.cell(
            self.epw / 2, 5, f"Cert. No. {self._cert_number}", align="R",
            new_x="LMARGIN", new_y="NEXT",
        )
        if self.page_no() != 1:
            self._rule()
            self.ln(5)
            return

        self.ln(2)
        crest_width = 21
        self.image(_COAT_OF_ARMS, x=(self.w - crest_width) / 2, w=crest_width)
        self.set_font(FONT, style="B", size=11)
        self.multi_cell(
            0, 5.5,
            "REPUBLIC OF KENYA\nIN THE SMALL CLAIMS COURT\n"
            "AT ________________________\nSCC CLAIM NO. __________ OF ________",
            align="C", new_x="LMARGIN", new_y="NEXT",
        )
        self.ln(4)
        self.set_font(FONT, style="B", size=9)
        self.cell(0, 5, "BETWEEN", new_x="LMARGIN", new_y="NEXT")
        for party in ("CLAIMANT", "RESPONDENT"):
            if party == "RESPONDENT":
                self.cell(0, 5, "VERSUS", align="C", new_x="LMARGIN", new_y="NEXT")
            self.cell(self.epw - 35, 6, "_" * 66)
            self.cell(35, 6, party, align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(1)
        self._rule()
        self.ln(0.8)
        self._rule()
        self.ln(4)

    def footer(self):
        self.set_y(-19)
        self._rule()
        self.ln(2)
        self.set_font("Helvetica", size=7)
        self.set_text_color(82, 89, 84)
        self.multi_cell(
            0, 3.4, _FOOTER_TEXT, align="C", new_x="LMARGIN", new_y="NEXT",
        )
        self.cell(0, 4, f"Page {self.page_no()} of {{nb}}", align="C")

    def _rule(self):
        self.set_draw_color(*_RULE)
        self.set_line_width(0.25)
        self.line(self.l_margin, self.y, self.w - self.r_margin, self.y)

    def document_title(self, heading: str, subtitle: str):
        self.set_font(FONT, style="B", size=19)
        self.multi_cell(0, 8, heading, align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font(FONT, size=11)
        self.multi_cell(0, 6, subtitle, align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(5)

    def section_heading(self, text: str):
        if self.will_page_break(20):
            self.add_page()
        self.set_font(FONT, style="B", size=11)
        self.set_fill_color(232, 237, 233)
        self.multi_cell(
            0, 7, _safe(text), fill=True, new_x="LMARGIN", new_y="NEXT",
        )
        self.set_fill_color(255, 255, 255)
        self.ln(1.5)

    def body(self, text: str):
        self.set_font(FONT, size=11)
        self.multi_cell(0, 5, _safe(text), align="L", new_x="LMARGIN", new_y="NEXT")
        self.ln(1.5)

    def list_item(self, marker: str, text: str):
        if self.will_page_break(5):
            self.add_page()
        self.set_font(FONT, size=11)
        self.cell(9, 5, marker)
        self.multi_cell(0, 5, _safe(text), align="L", new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def signature_fields(self):
        if self.will_page_break(26):
            self.add_page()
        self.set_y(max(self.y + 8, self.page_break_trigger - 16))
        self.set_font(FONT, size=10)
        self.cell(105, 5, "DATED at ____________________ this")
        self.cell(0, 5, "_" * 30, align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(105, 6, "_____ day of __________________, ________")
        self.set_font(FONT, style="B", size=9)
        self.cell(0, 6, "SIGNATURE OF DECLARANT", align="C", new_x="LMARGIN", new_y="NEXT")


# ---------------------------------------------------------------------------
# Evidence schedule (shared by both document types)
# ---------------------------------------------------------------------------

def _add_evidence_schedule(pdf: _CertPDF, evidence: list[dict], *, court_style: bool = False):
    """Add a table of evidence items (No., file name, type, date, SHA-256)."""
    if not evidence:
        pdf.body("No evidence items listed.")
        return

    pdf.set_font("Helvetica", size=8)
    with pdf.table(
        col_widths=(10, 58, 31, 23, 48), line_height=4, padding=1.5,
        headings_style=FontFace(emphasis="BOLD") if court_style else _TABLE_HEADING,
        borders_layout="HORIZONTAL_LINES" if court_style else "ALL",
        text_align="LEFT", wrapmode="CHAR",
    ) as table:
        type_heading = "Description" if court_style else "Type"
        table.row(("No.", "File name", type_heading, "Date added", "SHA-256 fingerprint"))
        for idx, item in enumerate(evidence, 1):
            evidence_type = str(item.get("type") or "")
            if court_style:
                evidence_type = _EVIDENCE_TYPE_LABELS.get(evidence_type, evidence_type)
            table.row((
                str(idx),
                _safe(str(item.get("file_name") or "")),
                _safe(evidence_type),
                _safe(str(item.get("added_at") or "")[:10]),
                _safe(str(item.get("server_sha256") or item.get("sha256") or "N/A")),
            ))
    pdf.ln(3)


# ---------------------------------------------------------------------------
# Contract analysis section (shared by both document types)
# ---------------------------------------------------------------------------

def _add_contract_analysis_section(
    pdf: _CertPDF, record: dict, heading: str = "Contract Analysis",
):
    """Add an element-by-element contract analysis table to the PDF."""
    derived  = record.get("derived_statuses") or {}
    result_e = (record.get("result") or {}).get("elements") or {}
    confidence = record.get("confidence")
    verdict    = record.get("verdict") or ""

    # Build a unified status map: prefer derived_statuses (authoritative)
    statuses: dict = {}
    for letter in _ELEMENT_LABELS:
        if letter in derived:
            statuses[letter] = derived[letter]
        elif letter in result_e:
            statuses[letter] = (result_e[letter].get("status") or "")
        else:
            statuses[letter] = ""

    conf_pct    = f"{round((confidence or 0) * 100)}%" if confidence is not None else "N/A"
    verdict_str = _safe(verdict) if verdict else "N/A"

    pdf.section_heading(heading)
    pdf.body(
        "A tick means satisfied or not required. A cross means not established. "
        "A dash means the analysis status is unavailable."
    )
    pdf.body(f"Contract verdict: {verdict_str}   |   Confidence: {conf_pct}")

    pdf.set_font("Helvetica", size=8)
    with pdf.table(
        col_widths=(10, 40, 25, 95), line_height=4, padding=1.5,
        headings_style=_TABLE_HEADING, text_align="LEFT",
    ) as table:
        table.row(("Ref.", "Element", "Status", "Description"))
        for letter, label in _ELEMENT_LABELS.items():
            status = str(statuses[letter]).strip().upper()
            row = table.row()
            row.cell(letter)
            row.cell(label)
            if status in _MET_STATUSES:
                row.cell("3", style=_TICK, align="CENTER")
            elif status in _UNMET_STATUSES:
                row.cell("7", style=_CROSS, align="CENTER")
            else:
                row.cell("—", align="CENTER")
            row.cell(_ELEMENT_DESC[letter])
    pdf.ln(3)


