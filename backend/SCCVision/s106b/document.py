"""Generate Section 106B certificate or deficiency report PDFs with fpdf2.

render_pdf(record) → bytes

The function is deterministic for the same record: it uses record["created_at"]
(not the current time) so the same record always produces the same bytes after
normalising fpdf2's creation-date metadata field.
"""

from __future__ import annotations

import datetime
from io import BytesIO

from fpdf import FPDF  # fpdf2


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

FONT = "Helvetica"

_FOOTER_TEXT = (
    "Generated by the SCC Evidence Assistant (prototype). "
    "This draft is not legal advice and has no legal effect until reviewed "
    "and signed by the declarant."
)
_HEADER_TEXT = "DRAFT - FOR REVIEW AND SIGNATURE"

# Map ProductionMethod values to plain-language descriptions
_PRODUCTION_METHOD_LABELS = {
    "screenshot_on_device": "Screenshot taken on the device that holds the messages",
    "forwarded_or_copied":  "Forwarded or copied from another device",
    "printed_statement":    "Printed statement produced by the device",
    "other":                "Other (not specified)",
}


# ---------------------------------------------------------------------------
# Latin-1 sanitisation (fpdf2 core fonts are Latin-1)
# ---------------------------------------------------------------------------

def _safe(text: str) -> str:
    """Replace characters outside Latin-1 with '?'."""
    if not text:
        return ""
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _safe_list(items: list) -> list[str]:
    return [_safe(str(i)) for i in items if i]


# ---------------------------------------------------------------------------
# Base PDF class
# ---------------------------------------------------------------------------

class _CertPDF(FPDF):
    def __init__(self, cert_number: str, created_at: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self._cert_number = _safe(cert_number)
        self._created_at  = _safe(created_at[:10] if created_at else "")
        self.set_margins(20, 20, 20)
        self.set_auto_page_break(auto=True, margin=25)
        self.add_page()

    def header(self):
        self.set_font(FONT, style="B", size=8)
        self.set_text_color(180, 50, 50)
        self.cell(0, 6, _HEADER_TEXT, align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.set_font(FONT, size=8)
        self.cell(0, 5,
                  f"Certificate No.: {self._cert_number}   |   Date: {self._created_at}",
                  align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(2)
        self.set_draw_color(180, 160, 100)
        self.set_line_width(0.4)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(3)

    def footer(self):
        self.set_y(-20)
        self.set_draw_color(180, 160, 100)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.set_font(FONT, size=7)
        self.set_text_color(100, 100, 100)
        self.cell(0, 5, _safe(_FOOTER_TEXT), align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)
        self.set_font(FONT, size=7)
        self.cell(0, 4, f"Page {self.page_no()}", align="C")

    # --- helpers -----------------------------------------------------------

    def section_heading(self, text: str):
        self.set_font(FONT, style="B", size=11)
        self.set_fill_color(240, 235, 215)
        self.cell(0, 8, _safe(text), fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)
        self.set_font(FONT, size=10)

    def body(self, text: str):
        self.set_font(FONT, size=10)
        self.multi_cell(0, 6, _safe(text))
        self.ln(1)

    def bullet(self, text: str, indent: float = 5):
        x = self.get_x()
        self.set_x(self.l_margin + indent)
        self.set_font(FONT, size=10)
        self.multi_cell(0, 6, _safe(f"•  {text}"))
        self.set_x(x)

    def blank_line(self, label: str):
        self.set_font(FONT, style="B", size=10)
        self.cell(50, 7, _safe(label + ":"))
        self.set_font(FONT, size=10)
        self.cell(0, 7, "_" * 48, new_x="LMARGIN", new_y="NEXT")


# ---------------------------------------------------------------------------
# Evidence schedule (shared by both document types)
# ---------------------------------------------------------------------------

def _add_evidence_schedule(pdf: _CertPDF, evidence: list[dict]):
    """Add a table of evidence items (No., file name, type, date, SHA-256)."""
    pdf.set_font(FONT, style="B", size=9)
    col_w = [10, 55, 35, 28, 42]
    headers = ["No.", "File name", "Type", "Date added", "SHA-256 (server)"]
    for i, h in enumerate(headers):
        pdf.cell(col_w[i], 7, h, border=1)
    pdf.ln()

    pdf.set_font(FONT, size=8)
    for idx, ev in enumerate(evidence, 1):
        fn   = _safe(str(ev.get("file_name") or ""))[:40]
        etype = _safe(str(ev.get("type") or ""))
        added = _safe(str(ev.get("added_at") or "")[:10])
        sha  = _safe(str(ev.get("server_sha256") or ev.get("sha256") or "N/A"))

        # Wrap SHA-256 in two parts if present
        sha_display = sha[:20] + "..." + sha[-8:] if len(sha) > 32 else sha

        pdf.cell(col_w[0], 6, str(idx), border=1)
        pdf.cell(col_w[1], 6, fn, border=1)
        pdf.cell(col_w[2], 6, etype, border=1)
        pdf.cell(col_w[3], 6, added, border=1)
        pdf.cell(col_w[4], 6, sha_display, border=1)
        pdf.ln()

    pdf.ln(2)


# ---------------------------------------------------------------------------
# CERTIFICATE layout
# ---------------------------------------------------------------------------

def _parse_created_at(created_at: str) -> datetime.datetime:
    """Parse a date string to a UTC datetime for deterministic PDF metadata."""
    try:
        date_part = str(created_at)[:10]  # "YYYY-MM-DD"
        return datetime.datetime(
            int(date_part[:4]), int(date_part[5:7]), int(date_part[8:10]),
            tzinfo=datetime.timezone.utc,
        )
    except (ValueError, IndexError):
        return datetime.datetime(2000, 1, 1, tzinfo=datetime.timezone.utc)


def _render_certificate(record: dict) -> FPDF:
    cert_number = record.get("certificate_number", "")
    created_at  = record.get("created_at", "")
    if hasattr(created_at, "isoformat"):
        created_at = created_at.isoformat()
    created_at = str(created_at)[:10]

    device      = record.get("device_facts") or {}
    evidence    = record.get("evidence") or []
    gate        = record.get("gate") or {}
    conditions  = gate.get("conditions") or []

    prod_method = device.get("production_method", "")
    prod_label  = _PRODUCTION_METHOD_LABELS.get(prod_method, prod_method)
    last4       = device.get("phone_number_last4") or ""
    phone_disp  = f"******{last4}" if last4 else "(not provided)"

    pdf = _CertPDF(cert_number, created_at)
    pdf.set_creation_date(_parse_created_at(created_at))  # deterministic metadata

    # Title
    pdf.set_font(FONT, style="B", size=14)
    pdf.multi_cell(
        0, 8,
        "Certificate in respect of Electronic Records\n"
        "Section 106B(4), Evidence Act (Cap. 80)",
        align="C",
    )
    pdf.ln(4)

    # --- Part A: s.106B(4)(a) ---
    pdf.section_heading("Part A — Identification of the Electronic Record (s.106B(4)(a))")
    pdf.body(
        f"The following electronic records form the subject of this certificate. "
        f"They were produced by the method described below."
    )
    _add_evidence_schedule(pdf, evidence)
    pdf.body(f"Manner of production: {prod_label}.")

    # --- Part B: s.106B(4)(b) ---
    pdf.section_heading("Part B — Particulars of the Device (s.106B(4)(b))")
    pdf.body(f"Device make:  {_safe(device.get('device_make', ''))}")
    pdf.body(f"Device model: {_safe(device.get('device_model', ''))}")
    pdf.body(f"Phone number: {phone_disp}")

    # --- Part C: s.106B(4)(c) — conditions 2(a)–2(d) ---
    pdf.section_heading("Part C — Conditions Under s.106B(2) (s.106B(4)(c))")
    decl = _safe(device.get("declarant_name") or "the declarant")

    c_statements = {
        "2a": (
            f"During the period covered by these records, the device was regularly "
            f"used by me and was under my lawful control."
        ),
        "2b": (
            "Information of the kind contained in the electronic records (messages "
            "and/or M-Pesa transactions) was regularly fed into the device in the "
            "ordinary course of my activities during that period."
        ),
        "2c_ok": (
            "Throughout the material period the device was operating properly, "
            "and no malfunction affected the accuracy of the records."
        ),
        "2c_mal": None,
        "2d": (
            "The information in the electronic records reproduces, or is derived "
            "from, information fed into the device in the ordinary course of those "
            "activities."
        ),
    }

    # Determine 2c statement
    cond_2c = next((c for c in conditions if c.get("code") == "2c"), None)
    if cond_2c and cond_2c.get("met"):
        mal_det = device.get("malfunction_details")
        if mal_det and not device.get("operating_properly", True):
            stmt_2c = (
                f"During the material period the device experienced a malfunction "
                f"({_safe(mal_det)}), but this malfunction did not affect the "
                "electronic record or the accuracy of its contents."
            )
        else:
            stmt_2c = c_statements["2c_ok"]
    else:
        stmt_2c = None  # 2c unmet — should not reach CERTIFICATE path

    for i, (key, stmt) in enumerate([
        ("(a)", c_statements["2a"]),
        ("(b)", c_statements["2b"]),
        ("(c)", stmt_2c),
        ("(d)", c_statements["2d"]),
    ], 1):
        if stmt:
            pdf.set_font(FONT, style="B", size=10)
            pdf.cell(12, 6, f"{i}.")
            pdf.set_font(FONT, size=10)
            pdf.multi_cell(0, 6, _safe(stmt))
            pdf.ln(1)

    # --- Part D: s.106B(4)(d) — Declaration ---
    pdf.section_heading("Part D — Declaration (s.106B(4)(d))")
    pos   = _safe(device.get("declarant_position") or "owner and operator of the device")
    pdf.body(
        f"I, {decl}, {pos}, certify that the statements above are true to the "
        f"best of my knowledge and belief."
    )
    pdf.ln(4)
    pdf.blank_line("Signature")
    pdf.ln(2)
    pdf.blank_line("National ID No.")
    pdf.ln(2)
    pdf.blank_line("Date")
    pdf.ln(2)
    pdf.blank_line("Place")

    return pdf


