const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

export const phoneCountries = REGION_GROUPS.flatMap(([code, regions, trunkPrefix, lengths]) =>
  regions.split(" ").map((region) => ({
    region,
    code: `+${code}`,
    name: regionNames.of(region) ?? region,
    trunkPrefix,
    lengths,
  })),
).sort((a, b) => a.name.localeCompare(b.name, "en"));

export function internationalPhoneNumber(input: string, region: string): string | null {
  const country = phoneCountries.find((option) => option.region === region);
  if (!country || !/^\+?[\d\s().-]+$/.test(input.trim())) return null;

  const digits = input.replace(/[^+\d]/g, "");
  const isInternational = digits.startsWith("+");
  if (isInternational && !digits.startsWith(country.code)) return null;

  let national = isInternational ? digits.slice(country.code.length) : digits;
  const withoutPrefix = national.slice(country.trunkPrefix.length);
  if (!isInternational && country.trunkPrefix && national.startsWith(country.trunkPrefix) &&
      country.lengths.includes(withoutPrefix.length) &&
      (country.trunkPrefix === "0" || !country.lengths.includes(national.length))) {
    national = withoutPrefix;
  }

  const normalized = country.code + national;
  return country.lengths.includes(national.length) && /^\+[1-9]\d{6,14}$/.test(normalized)
    ? normalized
    : null;
}
